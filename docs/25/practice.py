goods = {
    "A1": ["кеды", "спортивная обувь", 2500],
    "A2": ["ботинки", "демисезонная обувь", 4800],
    "A3": ["сандалии", "летняя обувь", 1900]
}
sku = input("Артикул товара: ")

if sku in goods:
    item = goods[sku]
    print("Артикул:", sku)
    print("Название:", item[0])
    print("Категория:", item[1])
    print("Цена:", format(item[2], ".2f"), "руб.")
else:
    print("Товар не найден")
